#!/bin/sh
# Перечитывание конфигурации по кругу.
#
# Лежит в каталоге, который entrypoint образа выполняет ПЕРЕД запуском nginx. Так и задумано:
# подменить саму команду запуска нельзя — entrypoint подставляет переменные в шаблоны только
# когда команда начинается с `nginx`, и подмена тихо оставила бы конфигурацию с неподставленным
# именем машины. Сертификат при этом читался бы по несуществующему пути.
#
# Зачем цикл: nginx читает файлы сертификата ОДИН раз при старте. Сертификат живёт неделю и
# меняется под ним на диске — без перечитывания вход продолжал бы отдавать просроченный, имея
# свежий в полуметре.
(
  while :; do
    sleep 6h
    nginx -s reload 2>/dev/null || true
  done
) &
